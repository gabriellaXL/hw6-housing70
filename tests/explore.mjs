import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const checks=[],errors=[];
page.on('pageerror',e=>errors.push(e.message));
const check=(name,test)=>{assert.ok(test,name);checks.push(name);};
const base=process.env.TEST_URL||'http://127.0.0.1:8766/';
await mkdir('test-results',{recursive:true});
try{
  await page.goto(base);await page.waitForFunction(()=>window.housingApp?.explorer);
  check('minority rule finds the five counter-direction cities',await page.evaluate(()=>housingApp.explorer.discover().found.length===5));
  check('cards explain why each city is different',await page.locator('.unusual-reason').first().textContent().then(s=>s.includes('占多数')));
  const before=await page.evaluate(()=>({c:[...housingApp.state.compare],s:[...housingApp.state.selected]}));
  await page.locator('.unusual-card').first().click();
  check('click opens a separate enlarged view',await page.locator('#city-detail').evaluate(el=>el.open));
  check('inspection preserves comparison and brush',await page.evaluate(b=>JSON.stringify(b)===JSON.stringify({c:[...housingApp.state.compare],s:[...housingApp.state.selected]}),before));
  check('enlarged view includes trend, scatter and three heat rows',await page.locator('#detail-trend svg').count()===1&&await page.locator('#detail-scatter .detail-focus-dot').count()===1&&await page.locator('#detail-heat td').count()===99);
  check('69 other cities remain contextual scatter marks',await page.locator('.detail-context-dot').count()===69);
  check('benchmark excludes the inspected city',await page.evaluate(()=>{
    const a=housingApp,city=a.state.detailCity,group=a.cities.filter(c=>c!==city).map(c=>a.pair(c,a.state.month,a.state.metric).n).filter(v=>v!=null).sort((a,b)=>a-b);
    const med=(group[34]);return document.querySelector('#detail-stats').textContent.includes((med>0?'+':'')+med.toFixed(1));
  }));
  const firstCity=await page.evaluate(()=>housingApp.state.detailCity);
  await page.locator('#detail-next-city').click();
  check('navigate through the candidate cities',await page.evaluate(c=>housingApp.state.detailCity!==c,firstCity));
  await page.locator('[data-detail-type=resale]').click();
  check('type switch updates the enlarged trend',await page.locator('#detail-line-label').textContent().then(s=>s.includes('二手房')));
  await page.locator('#detail-zoom').uncheck();
  check('full-scale option and explicit scale note',await page.locator('#detail-scale-note').textContent().then(s=>s.startsWith('总览尺度')));
  await page.locator('#detail-zoom').check();
  await page.locator('#detail-month-prev').click();
  check('detail month navigation updates main month',await page.evaluate(()=>housingApp.state.month==='2026-08'));
  check('detail stays open during month navigation',await page.locator('#city-detail').evaluate(el=>el.open));
  await page.locator('#detail-city').selectOption('北京');
  const viewport=await page.locator('#detail-trend svg').boundingBox();
  await page.mouse.move(viewport.x+viewport.width*.5,viewport.y+viewport.height*.5);
  check('tooltip is visible within modal top layer',await page.locator('#city-detail #tooltip').isVisible());
  await page.locator('#detail-heat td[data-month="2024-01"]').first().click();
  check('detail heat cell navigates month',await page.evaluate(()=>housingApp.state.month==='2024-01'));
  await page.reload();await page.waitForFunction(()=>window.housingApp?.explorer);
  check('share URL restores city, chart type, month and zoom',await page.evaluate(()=>housingApp.state.detailCity==='北京'&&housingApp.state.detailType==='resale'&&housingApp.state.month==='2024-01'&&housingApp.state.detailZoom)&&await page.locator('#city-detail').evaluate(el=>el.open));
  await page.keyboard.press('Escape');
  check('Escape closes dialog and clears URL detail',await page.locator('#city-detail').evaluate(el=>!el.open)&&!new URL(page.url()).searchParams.has('detail'));
  await page.locator('[data-unusual=turn]').click();
  check('first month clearly explains missing previous month',await page.locator('#unusual-rule').textContent().then(s=>s.includes('没有前月'))&&await page.locator('.unusual-card').count()===0);
  await page.locator('#reset').click();await page.locator('[data-unusual=gap]').click();
  check('largest-gap city is ranked first using actual data',await page.locator('.unusual-card strong').first().textContent().then(s=>s==='杭州')&&await page.locator('.unusual-card').count()===5);
  await page.locator('.unusual-card').first().click();
  check('gap opens directly on the difference series',await page.evaluate(()=>housingApp.state.detailType==='gap'));
  await page.screenshot({path:'test-results/detail-desktop.png'});
  await page.locator('#detail-close').click();await page.locator('[data-unusual=turn]').click();
  check('turn candidates really changed sign since previous release',await page.evaluate(()=>housingApp.explorer.discover().found.every(d=>{
    const p=housingApp.pair(d.city,'2026-08','yoy');return d.n*p.n<0||d.r*p.r<0;
  })));
  await page.locator('#reset').click();
  await page.getByRole('button',{name:'放大查看北京',exact:true}).click();
  check('ordinary trend card can also be enlarged',await page.evaluate(()=>housingApp.state.detailCity==='北京'));
  await page.setViewportSize({width:390,height:844});
  check('mobile dialog fits viewport',await page.locator('#city-detail').evaluate(el=>el.getBoundingClientRect().width<=innerWidth));
  check('detail heatmap scrolls internally',await page.locator('.detail-heat-scroll').evaluate(el=>el.scrollWidth>el.clientWidth));
  await page.screenshot({path:'test-results/detail-mobile.png'});
  await page.locator('#detail-close').click();await page.locator('#reset').click();
  await page.evaluate(()=>housingApp.setSelected(['杭州','大理']));
  await page.locator('#inspect-selected').click();
  check('brush selection can be inspected city by city',await page.locator('#detail-candidate').textContent().then(s=>s.includes('/ 2 城')));
  await page.locator('#detail-close').click();
  check('no runtime errors',errors.length===0);
  await writeFile('test-results/explore.json',JSON.stringify({base,passed:checks.length,checks,errors},null,2));
  console.log(`PASS ${checks.length} city-inspection checks`);
}finally{await browser.close();}
