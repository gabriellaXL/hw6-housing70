import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';

const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1050}}),errors=[],checks=[];
page.on('pageerror',e=>errors.push(e.message));
const check=(name,condition)=>{assert.ok(condition,name);checks.push(name);};
try {
  await page.goto(process.env.PREVIEW_URL||'http://127.0.0.1:8766/preview/classic.html');
  await page.waitForFunction(()=>window.housingPreview);
  check('70 real city marks',await page.locator('.city-dot').count()===70);
  check('Hangzhou real values',await page.locator('#new-value').textContent()==='+1.8%');
  await page.getByRole('button',{name:/查看上海，新房/}).click();
  check('scatter selection updates adjacent city',await page.locator('#city-name').textContent()==='上海');
  check('city change updates values',await page.locator('#new-value').textContent()==='+2.8%');
  await page.locator('#prev').click();
  check('month control updates date',await page.locator('#month-label').textContent()==='2026.08');
  const domain=await page.evaluate(()=>housingPreview.limits.yoy.domain);
  await page.locator('#prev').click();
  check('scatter scale remains fixed across months',JSON.stringify(domain)===JSON.stringify(await page.evaluate(()=>housingPreview.limits.yoy.domain)));
  await page.locator('[data-metric=mom]').click();
  check('metric updates data and labels',await page.evaluate(()=>housingPreview.state.metric==='mom'&&document.querySelector('#scatter-subtitle').textContent.includes('环比')));
  await page.locator('[data-metric=yoy]').click();
  await page.locator('[data-explore=gap]').click();
  check('exploration selects actual largest five gaps',await page.evaluate(()=>{const s=housingPreview.state;const expected=[...new Set(document.querySelectorAll('.city-dot.brushed').values())].length;return s.selected.size===5&&expected===5;}));
  check('group selection updates adjacent history',await page.locator('#city-name').textContent()==='5 座城市');
  await page.locator('#clear').click();
  const box=await page.locator('#scatter svg').boundingBox();
  await page.mouse.move(box.x+290,box.y+145);await page.mouse.down();await page.mouse.move(box.x+560,box.y+330,{steps:15});await page.mouse.up();
  check('actual pointer brush selects cities',await page.evaluate(()=>housingPreview.state.selected.size>0&&housingPreview.state.selected.size<70));
  await page.locator('#clear').click();
  await page.locator('#city-search').fill('成都');await page.locator('#search-form').press('Enter');
  check('city search updates detail',await page.locator('#city-name').textContent()==='成都');
  await page.locator('#pin').click();
  check('pin adds comparison',await page.locator('.compare-card').count()===4);
  await page.getByRole('button',{name:'移除成都',exact:true}).click();
  check('comparison can be removed',await page.locator('.compare-card').count()===3);
  await page.locator('#heat-details summary').click();
  check('heatmap has 70 cities and 33 months',await page.locator('#heatmap td').count()===2310);
  await page.locator('#heatmap td[data-city="北京"][data-month="2024-01"]').click();
  check('heat cell updates month and city',await page.evaluate(()=>housingPreview.state.city==='北京'&&housingPreview.state.month==='2024-01'));
  await page.locator('#play').click();await page.waitForTimeout(1000);await page.locator('#play').click();
  check('playback advances month and pauses',await page.evaluate(()=>housingPreview.state.month==='2024-02'&&!housingPreview.state.playing));
  await page.goto('http://127.0.0.1:8766/preview/classic.html?m=2026-09&city=杭州');await page.waitForFunction(()=>window.housingPreview);
  await mkdir('test-results',{recursive:true});await page.screenshot({path:'test-results/preview-desktop.png',fullPage:true});await page.screenshot({path:'test-results/preview-first-screen.png'});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(250);
  check('mobile has no horizontal page overflow',await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  check('mobile trends use full card width',await page.locator('.compare-chart svg').first().evaluate(el=>Math.abs(Number(el.getAttribute('viewBox').split(' ')[2])-el.clientWidth)<2));
  await page.screenshot({path:'test-results/preview-mobile.png',fullPage:true});
  await page.locator('#heat-details summary').click();
  check('mobile heatmap has its own scrolling area',await page.locator('.heat-scroll').evaluate(el=>el.scrollWidth>el.clientWidth));
  check('no uncaught browser errors',errors.length===0);
  await writeFile('test-results/preview-checks.json',JSON.stringify({checks,errors},null,2));
  console.log(`PASS ${checks.length} preview checks`);
} finally {await browser.close();}
